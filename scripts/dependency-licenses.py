#!/usr/bin/env python3
"""Collect the locked crates' license texts; --check verifies the committed bundle."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'third_party/rust/CRATE_LICENSES.txt'


def render():
    metadata = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--offline', '--format-version', '1'],
        cwd=ROOT, text=True, encoding='utf-8'))
    sections = ['Rust crate licenses from Cargo.lock.\n'
                'Includes build, test and platform-specific dependencies.\n'
                'Generated by scripts/dependency-licenses.py; upstream terms apply.\n']
    for package in sorted(metadata['packages'], key=lambda p: (p['name'], p['version'])):
        if package['source'] is None:
            continue
        root = Path(package['manifest_path']).parent
        files = sorted(p for p in root.iterdir() if p.is_file()
                       and p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE')))
        # r-efi publishes its licensing terms in README.md, not a separate file.
        if not files and package['name'] == 'r-efi':
            files = [root / 'README.md']
        if not files:
            raise RuntimeError('Missing license texts for ' + package['name'])
        sections.append(f"\n{'=' * 72}\n{package['name']} {package['version']}\n"
                        f"License: {package['license']}\n"
                        f"Source: https://crates.io/crates/{package['name']}/{package['version']}\n")
        for path in files:
            sections.append(f'\n--- {path.name} ---\n' + path.read_text(encoding='utf-8').rstrip() + '\n')
    return ''.join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit('Crate licenses are stale; run python scripts/dependency-licenses.py')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
